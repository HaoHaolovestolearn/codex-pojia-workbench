const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
(async () => {
 const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];
 page.on('pageerror', error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:8765');
 await page.getByRole('button',{name:'创建任务说明 ↗',exact:true}).click();
 await page.locator('#goal').fill('修复示例中的空值处理');
 await page.getByRole('button',{name:'生成任务说明 ↗',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#prompt-output').textContent.includes('修复示例中的空值处理'));
 await page.locator('nav button[data-view="requests"]').click();
 await page.locator('#provider').selectOption('deepseek');
 await page.getByRole('button',{name:'检查并生成示例 ↗',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#code-output').textContent.includes('urllib.request'));
 await page.locator('#language').selectOption('JavaScript');
 await page.waitForFunction(()=>document.querySelector('#code-output').textContent.includes('fetch('));
 await page.getByRole('button',{name:'本地保存配置',exact:true}).click();
 await page.waitForFunction(()=>localStorage.getItem('nb.workbench.profile.v1'));
 const saved = await page.evaluate(()=>JSON.parse(localStorage.getItem('nb.workbench.profile.v1')));
 if (Object.keys(saved).sort().join(',')!=='base,model,protocol') throw Error('Unexpected saved fields');
 await page.locator('nav button[data-view="budget"]').click();
 await page.getByRole('button',{name:'计算估算费用 ↗',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#budget-total').textContent==='0.40000000');
 await page.locator('nav button[data-view="errors"]').click();
 await page.locator('#error-search').fill('429');
 if(await page.locator('.error-card').count()!==1) throw Error('Error search did not filter');
 await page.locator('nav button[data-view="home"]').click();
 const out=path.join(__dirname,'..','dist','ui'); fs.mkdirSync(out,{recursive:true});
 await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
 const overflow = await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow) throw Error('Horizontal overflow on mobile');
 if(errors.length) throw Error(errors.join('\n'));
 console.log(JSON.stringify({uiChecks:8,javascriptErrors:errors.length,mobileOverflow:overflow,screenshots:true}));
 await browser.close();
})().catch(error=>{console.error(error.message);process.exit(1)});
